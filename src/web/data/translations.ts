export const translateText = (
  text: string,
  lang: AppLanguage,
  hiFallback?: string,
  customMap?: Partial<Record<AppLanguage, string>>
): string => {
  if (lang === 'en') {
    return text;
  }

  // Check custom multi-language map passed to t()
  if (customMap && customMap[lang]) {
    return customMap[lang]!;
  }

  // Check central dictionary translation map
  const entry = TRANSLATION_MAP[text];
  if (entry && entry[lang]) {
    return entry[lang];
  }

  // Only fall back to Hindi if the user's selected language is Hindi
  if (lang === 'hi') {
    if (customMap && customMap.hi) return customMap.hi;
    if (entry && entry.hi) return entry.hi;
    if (hiFallback) return hiFallback;
  }

  // For other regional languages without a specific translation, return English base text to avoid language mixing
  return text;
};
